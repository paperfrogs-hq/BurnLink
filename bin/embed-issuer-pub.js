#!/usr/bin/env node
// Build-time: read keys/issuer.pub and write its contents into
// lib/issuer-pub.js as an exported string constant. Bundled into
// the server so it works on serverless (Netlify Functions) without
// relying on file-path lookups that may not exist at runtime.

"use strict";

const fs = require("node:fs");
const path = require("node:path");

const pubPath = path.join(__dirname, "..", "keys", "issuer.pub");
const outPath = path.join(__dirname, "..", "lib", "issuer-pub.js");

if (!fs.existsSync(pubPath)) {
  console.error(`error: missing ${pubPath}. Generate a keypair first.`);
  process.exit(1);
}

const pem = fs.readFileSync(pubPath, "utf8");
const js = `// AUTO-GENERATED by bin/embed-issuer-pub.js — do not edit.\n` +
  `module.exports = ${JSON.stringify(pem)};\n`;
fs.writeFileSync(outPath, js);
console.log(`✓ wrote ${outPath} (${pem.length} bytes)`);
